CREATE TABLE IF NOT EXISTS public.sms (
    id_sms bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contenu_sms varchar(255),
    date_enregistrement_sms timestamp,
    date_envoi_sms timestamp,
    heure_enregistrement_sms time,
    heure_envoi_sms time,
    numero_destinataire varchar(255),
    numero_expediteur varchar(255),
    statut varchar(255),
    id_campagne bigint
);

ALTER TABLE public.sms ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS sms_authenticated_all ON public.sms;
CREATE POLICY sms_authenticated_all ON public.sms FOR ALL TO authenticated USING (true) WITH CHECK (true);
